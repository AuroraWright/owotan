import {parseJson} from '../core/json.js';

/**
 * Whether this context may share memory between threads, which the build with threads needs.
 * @returns {boolean}
 */
export function isCrossOriginIsolated() {
    return typeof crossOriginIsolated === 'boolean' && crossOriginIsolated;
}

/**
 * The hoshidicts dictionary engine, compiled to WebAssembly (dev/hoshidicts). Each instance has its own
 * heap and file system; requests are synchronous.
 */
export class Hoshidicts {
    /**
     * @param {import('hoshidicts').Module} module
     */
    constructor(module) {
        /** @type {import('hoshidicts').Module} */
        this._module = module;
        const {cwrap} = module;
        /** @type {(archivePath: string, outputDirectory: string) => string} */
        this._import = cwrap('yh_import', 'string', ['string', 'string']);
        /** @type {(path: string) => number} */
        this._add = cwrap('yh_add', 'number', ['string']);
        /** @type {(path: string) => void} */
        this._remove = cwrap('yh_remove', null, ['string']);
        /** @type {(request: string) => number} */
        this._findTerms = cwrap('yh_find_terms', 'number', ['string']);
        /** @type {(request: string) => number} */
        this._findTermsBySequence = cwrap('yh_find_terms_by_sequence', 'number', ['string']);
        /** @type {(request: string) => number} */
        this._getGlossaries = cwrap('yh_glossaries', 'number', ['string']);
        /** @type {(request: string) => number} */
        this._findTermMeta = cwrap('yh_find_term_meta', 'number', ['string']);
        /** @type {(request: string) => number} */
        this._findKanji = cwrap('yh_find_kanji', 'number', ['string']);
        /** @type {(request: string) => number} */
        this._findKanjiMeta = cwrap('yh_find_kanji_meta', 'number', ['string']);
        /** @type {(dictionary: string, path: string) => number} */
        this._getMedia = cwrap('yh_media', 'number', ['string', 'string']);
        /** @type {() => number} */
        this._getMediaSize = cwrap('yh_media_size', 'number', []);
        /** @type {TextDecoder} */
        this._textDecoder = new TextDecoder();
        /** @type {Uint8Array} */
        this._sharedCopy = new Uint8Array(0);
    }

    /**
     * @param {?number} [threadPoolSize] The number of threads to start with the build that has threads, which needs a
     *   cross-origin isolated context, or null for the build without. Only importing uses threads, and it waits for
     *   them, so an import needs a pool of its own and lookups need none.
     * @returns {Promise<Hoshidicts>}
     */
    static async create(threadPoolSize = null) {
        const threads = threadPoolSize !== null;
        // The module is generated by `npm run build:hoshidicts`; a variable specifier keeps it out of type checking.
        const moduleUrl = new URL(threads ? '../../lib/hoshidicts-threads.js' : '../../lib/hoshidicts.js', import.meta.url).href;
        // eslint-disable-next-line no-unsanitized/method
        const modulePromise = /** @type {Promise<{default: import('hoshidicts').CreateModule}>} */ (import(moduleUrl));
        const {default: createModule} = await modulePromise;
        return new Hoshidicts(await createModule(threads ? {threadPoolSize} : {}));
    }

    /** @type {import('hoshidicts').FileSystem} */
    get fs() {
        return this._module.FS;
    }

    /** @type {unknown} */
    get opfsFileSystem() {
        return this._module.OPFSFS;
    }

    /**
     * Imports a Yomitan dictionary archive.
     * @param {string} archivePath
     * @param {string} outputDirectory The directory to create the dictionary's directory in.
     * @returns {import('hoshidicts').ImportReport}
     */
    import(archivePath, outputDirectory) {
        return parseJson(this._import(archivePath, outputDirectory));
    }

    /**
     * Loads the dictionary at `path` for every kind of query. Its entries are read from the files on demand.
     * @param {string} path
     * @returns {boolean}
     */
    add(path) {
        return this._add(path) !== 0;
    }

    /**
     * @param {string} path
     */
    remove(path) {
        this._remove(path);
    }

    /**
     * Finds the term rows whose expression or reading is each key. Glossaries are not included.
     * @param {string[]} keys
     * @param {string[]} dictionaries The names of the dictionaries to look in. The others are not read.
     * @returns {import('hoshidicts').TermRow[][]}
     */
    findTerms(keys, dictionaries) {
        return this._request(this._findTerms, {keys, dictionaries});
    }

    /**
     * @param {[dictionary: string, sequence: number][]} items
     * @returns {import('hoshidicts').TermRow[][]}
     */
    findTermsBySequence(items) {
        return this._request(this._findTermsBySequence, items);
    }

    /**
     * @param {[dictionary: string, offset: number][]} items
     * @returns {(?unknown[])[]}
     */
    getGlossaries(items) {
        return this._request(this._getGlossaries, items);
    }

    /**
     * @param {string[]} keys
     * @param {string[]} dictionaries The names of the dictionaries to look in. The others are not read.
     * @returns {import('hoshidicts').MetaRow[][]}
     */
    findTermMeta(keys, dictionaries) {
        return this._request(this._findTermMeta, {keys, dictionaries});
    }

    /**
     * @param {string[]} keys
     * @param {string[]} dictionaries The names of the dictionaries to look in. The others are not read.
     * @returns {import('hoshidicts').KanjiRow[][]}
     */
    findKanji(keys, dictionaries) {
        return this._request(this._findKanji, {keys, dictionaries});
    }

    /**
     * @param {string[]} keys
     * @param {string[]} dictionaries The names of the dictionaries to look in. The others are not read.
     * @returns {import('hoshidicts').MetaRow[][]}
     */
    findKanjiMeta(keys, dictionaries) {
        return this._request(this._findKanjiMeta, {keys, dictionaries});
    }

    /**
     * @param {string} dictionary
     * @param {string} path
     * @returns {?ArrayBuffer}
     */
    getMedia(dictionary, path) {
        const pointer = this._getMedia(dictionary, path);
        const size = this._getMediaSize();
        if (pointer === 0 || size < 0) { return null; }
        return this._module.HEAPU8.slice(pointer, pointer + size).buffer;
    }

    // Private

    /**
     * @template [T=unknown]
     * @param {(request: string) => number} call
     * @param {unknown} request
     * @returns {T}
     * @throws {Error}
     */
    _request(call, request) {
        /** @type {unknown} */
        const result = parseJson(this._readString(call(JSON.stringify(request))));
        if (!Array.isArray(result)) {
            const {error} = /** @type {import('hoshidicts').ErrorResult} */ (result);
            throw new Error(`hoshidicts: ${error}`);
        }
        return /** @type {T} */ (result);
    }

    /**
     * Reads a string that the module returned. A heap shared between threads cannot be decoded in place, and
     * Emscripten would copy each string into a new buffer, which for large results kept many megabytes of
     * memory, so those are copied into one buffer that is kept.
     * @param {number} pointer
     * @returns {string}
     */
    _readString(pointer) {
        const heap = this._module.HEAPU8;
        const end = heap.indexOf(0, pointer);
        const bytes = heap.subarray(pointer, end);
        if (heap.buffer instanceof ArrayBuffer) { return this._textDecoder.decode(bytes); }
        if (this._sharedCopy.length < bytes.length) {
            this._sharedCopy = new Uint8Array(Math.max(bytes.length, this._sharedCopy.length * 2));
        }
        this._sharedCopy.set(bytes);
        return this._textDecoder.decode(this._sharedCopy.subarray(0, bytes.length));
    }
}
