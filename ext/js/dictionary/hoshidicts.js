import {parseJson} from '../core/json.js';

/**
 * The hoshidicts dictionary engine, compiled to WebAssembly (dev/hoshidicts). Each instance has its own
 * heap and file system; requests are synchronous.
 */
export class Hoshidicts {
    /**
     * @param {import('hoshidicts').Module} module
     */
    constructor(module) {
        /** @type {import('hoshidicts').Module} */
        this._module = module;
        const {cwrap} = module;
        /** @type {(archivePath: string, outputDirectory: string) => string} */
        this._import = cwrap('yh_import', 'string', ['string', 'string']);
        /** @type {(path: string, paged: number) => number} */
        this._add = cwrap('yh_add', 'number', ['string', 'number']);
        /** @type {(path: string) => void} */
        this._remove = cwrap('yh_remove', null, ['string']);
        /** @type {(request: string) => string} */
        this._findTerms = cwrap('yh_find_terms', 'string', ['string']);
        /** @type {(request: string) => string} */
        this._findTermsBySequence = cwrap('yh_find_terms_by_sequence', 'string', ['string']);
        /** @type {(request: string) => string} */
        this._getGlossaries = cwrap('yh_glossaries', 'string', ['string']);
        /** @type {(request: string) => string} */
        this._findTermMeta = cwrap('yh_find_term_meta', 'string', ['string']);
        /** @type {(request: string) => string} */
        this._findKanji = cwrap('yh_find_kanji', 'string', ['string']);
        /** @type {(request: string) => string} */
        this._findKanjiMeta = cwrap('yh_find_kanji_meta', 'string', ['string']);
        /** @type {(dictionary: string, path: string) => number} */
        this._getMedia = cwrap('yh_media', 'number', ['string', 'string']);
        /** @type {() => number} */
        this._getMediaSize = cwrap('yh_media_size', 'number', []);
    }

    /**
     * @param {boolean} [threads] Whether to load the build that imports dictionaries on several threads. It needs a
     *   cross-origin isolated context, and is only faster at importing.
     * @returns {Promise<Hoshidicts>}
     */
    static async create(threads = false) {
        // The module is generated by `npm run build:hoshidicts`; a variable specifier keeps it out of type checking.
        const moduleUrl = new URL(threads ? '../../lib/hoshidicts-threads.js' : '../../lib/hoshidicts.js', import.meta.url).href;
        // eslint-disable-next-line no-unsanitized/method
        const modulePromise = /** @type {Promise<{default: import('hoshidicts').CreateModule}>} */ (import(moduleUrl));
        const {default: createModule} = await modulePromise;
        return new Hoshidicts(await createModule());
    }

    /** @type {import('hoshidicts').FileSystem} */
    get fs() {
        return this._module.FS;
    }

    /** @type {unknown} */
    get opfsFileSystem() {
        return this._module.OPFSFS;
    }

    /**
     * Imports a Yomitan dictionary archive.
     * @param {string} archivePath
     * @param {string} outputDirectory The directory to create the dictionary's directory in.
     * @returns {import('hoshidicts').ImportReport}
     */
    import(archivePath, outputDirectory) {
        return parseJson(this._import(archivePath, outputDirectory));
    }

    /**
     * Loads the dictionary at `path` for every kind of query.
     * @param {string} path
     * @param {boolean} paged Whether entries are read from the files on demand rather than copied into memory.
     * @returns {boolean}
     */
    add(path, paged) {
        return this._add(path, paged ? 1 : 0) !== 0;
    }

    /**
     * @param {string} path
     */
    remove(path) {
        this._remove(path);
    }

    /**
     * Finds the term rows whose expression or reading is each key. Glossaries are not included.
     * @param {string[]} keys
     * @returns {import('hoshidicts').TermRow[][]}
     */
    findTerms(keys) {
        return this._request(this._findTerms, keys);
    }

    /**
     * @param {[dictionary: string, sequence: number][]} items
     * @returns {import('hoshidicts').TermRow[][]}
     */
    findTermsBySequence(items) {
        return this._request(this._findTermsBySequence, items);
    }

    /**
     * @param {[dictionary: string, offset: number][]} items
     * @returns {(?unknown[])[]}
     */
    getGlossaries(items) {
        return this._request(this._getGlossaries, items);
    }

    /**
     * @param {string[]} keys
     * @returns {import('hoshidicts').MetaRow[][]}
     */
    findTermMeta(keys) {
        return this._request(this._findTermMeta, keys);
    }

    /**
     * @param {string[]} keys
     * @returns {import('hoshidicts').KanjiRow[][]}
     */
    findKanji(keys) {
        return this._request(this._findKanji, keys);
    }

    /**
     * @param {string[]} keys
     * @returns {import('hoshidicts').MetaRow[][]}
     */
    findKanjiMeta(keys) {
        return this._request(this._findKanjiMeta, keys);
    }

    /**
     * @param {string} dictionary
     * @param {string} path
     * @returns {?ArrayBuffer}
     */
    getMedia(dictionary, path) {
        const pointer = this._getMedia(dictionary, path);
        const size = this._getMediaSize();
        if (pointer === 0 || size < 0) { return null; }
        return this._module.HEAPU8.slice(pointer, pointer + size).buffer;
    }

    // Private

    /**
     * @template [T=unknown]
     * @param {(request: string) => string} call
     * @param {unknown} request
     * @returns {T}
     * @throws {Error}
     */
    _request(call, request) {
        /** @type {unknown} */
        const result = parseJson(call(JSON.stringify(request)));
        if (!Array.isArray(result)) {
            const {error} = /** @type {import('hoshidicts').ErrorResult} */ (result);
            throw new Error(`hoshidicts: ${error}`);
        }
        return /** @type {T} */ (result);
    }
}
